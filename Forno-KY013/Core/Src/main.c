/* USER CODE BEGIN 4 */
void HAL_TIM_PeriodElapsedCallback (TIM_HandleTypeDef * htim) // É chamada à cada 1000ms == 1s
{
  if (htim->Instance == TIM4)
  {
    segundos++;

    // Leitura de Temperatura via ADC:
    HAL_GPIO_WritePin(GPIOA, ToggleTemp_Pin, 1); // Sinaliza inicio de leitura temp

    HAL_ADC_Start(&hadc1); // Inicia a conversão AD
    HAL_ADC_PollForConversion(&hadc1, 100); // Aguarda a conversão completar (timeout 100ms)
    ValTempADC = HAL_ADC_GetValue(&hadc1); // Lê o valor convertido (0-4095)
    
    //HAL_GPIO_WritePin(GPIOA, ToggleTemp_Pin, 0); // Sinaliza fim de leitura temp

    // Converte o valor lido para temperatura em graus Celsius
    ValTemp_mV = ((ValTempADC) / 4095.0) * 3300.0; // Converte para milivolts (considerando Vref = 3.3V)
    ValTemp = DividerVoltageToDegreesCelsius(3300.0, ValTemp_mV); // Calcula a temperatura
    
    ErroTemp = LimTemp - ValTemp;

    //Lida com os valores lidos de temperatura:
    if ((ValTemp >= (LimTemp+2)) || ((KErro*ErroTemp) < 0)) // Excesso de temperatura
      htim4.Instance->CCR1 = 0; // 0% Duty Cycle
    else if ((ValTemp <= (LimTemp-2)) || ((KErro*ErroTemp) > 100)) // Muito abaixo da temperatura
      htim4.Instance->CCR1 = htim4.Instance->ARR; // 100% Duty Cycle
    else // Controle Proporcional
      htim4.Instance->CCR1 = KErro*ErroTemp*(htim4.Instance->ARR); // Ajusta o Duty Cycle proporcionalmente ao erro de temperatura
 
    // Envia os dados via USB CDC
    sprintf(bufferT, "%d ; %d ; %d ;\r\n", segundos, ((int) ValTemp), LimTemp);
    CDC_Transmit_FS(bufferT, strlen(bufferT));
  }
}
